import { createAuthClient } from 'better-auth/react';

/**
 * baseURL намеренно не задаётся.
 *
 * Без него better-auth в браузере берёт `window.location.origin` — то есть
 * обращается ровно к тому домену, с которого открыта страница. Именно это и
 * нужно превью-деплоям: раньше здесь стоял NEXT_PUBLIC_APP_URL, который
 * вшивается в бандл на сборке и на превью указывал на продакшен, из-за чего
 * браузер отправлял запросы авторизации на чужой домен, а cookie ставились
 * не туда, где их потом ищут.
 *
 * При серверном рендере клиентских компонентов, где `window` недоступен,
 * better-auth подставляет VERCEL_URL текущего деплоя.
 *
 * Важно: переменная NEXT_PUBLIC_BETTER_AUTH_URL должна отсутствовать.
 * better-auth читает её раньше всех прочих источников, и одного её наличия
 * достаточно, чтобы снова прибить клиент к одному домену.
 */
export const authClient = createAuthClient();

// Экспортируем готовые хуки и методы для удобства
export const { signIn, signOut, signUp, useSession } = authClient;
